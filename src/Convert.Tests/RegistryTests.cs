public class RegistryTests
{
    static ConversionRegistry Registry => Fixtures.Registry;

    // The whole catalogue as one reviewed table: adding a pack, a route or an assembly shows as a diff
    // here and in docs/catalogue.md.
    [Test]
    public async Task Catalogue()
    {
        var builder = new StringBuilder();
        builder.AppendLine(
            """
            # Catalogue

            Generated by `RegistryTests.Catalogue`; do not edit by hand.

            ## Conversions

            | Source | Target | Tool | Priority | Options | Lazy assemblies |
            |---|---|---|---|---|---|
            """);
        foreach (var conversion in Registry
                     .Conversions
                     .OrderBy(_ => _.Source.Id)
                     .ThenBy(_ => _.Target.Id)
                     .ThenBy(_ => _.Priority))
        {
            var options = conversion.CreateOptions().GetType().Name;
            builder.AppendLine($"| {conversion.Source.Id} | {conversion.Target.Id} | {conversion.Tool.DisplayName} | {conversion.Priority} | {options} | {Names(conversion.Assemblies)} |");
        }

        builder.AppendLine(
            """

            ## Previews

            | Type | Component | Priority | Lazy assemblies |
            |---|---|---|---|
            """);
        foreach (var preview in Registry
                     .Previews
                     .OrderBy(_ => _.Type.Id)
                     .ThenBy(_ => _.Priority))
        {
            builder.AppendLine($"| {preview.Type.Id} | {preview.Component.Name} | {preview.Priority} | {Names(preview.Assemblies)} |");
        }

        builder.AppendLine(
            """

            ## Editors

            | Type | Component | Lazy assemblies |
            |---|---|---|
            """);
        foreach (var editor in Registry.Editors.OrderBy(_ => _.Type.Id))
        {
            builder.AppendLine($"| {editor.Type.Id} | {editor.Component.Name} | {Names(editor.Assemblies)} |");
        }

        builder.AppendLine(
            """

            ## Samples

            | Name | File | Asset |
            |---|---|---|
            """);
        foreach (var sample in Registry.Samples)
        {
            builder.AppendLine($"| {sample.DisplayName} | {sample.FileName} | `{sample.AssetUrl}` |");
        }

        var markdown = builder.ToString().ReplaceLineEndings("\n");
        await File.WriteAllTextAsync(Path.Combine(Fixtures.RepoRoot, "docs", "catalogue.md"), markdown);
        await Verify(markdown, "md");
    }

    static string Names(IReadOnlyList<string> assemblies)
    {
        if (assemblies.Count == 0)
        {
            return "—";
        }

        return string.Join(", ", assemblies.Order(StringComparer.Ordinal).Select(_ => _.Replace(".wasm", "")));
    }

    [Test]
    public async Task EveryReadableTypeHasAPreview()
    {
        var missing = Registry.Types
            .Where(_ => _.Kind == FileKind.Binary &&
                        Registry.PreviewsFor(_).Count == 0)
            .Select(_ => _.Id)
            .ToList();
        // Publisher has no viewer in the browser; its PDF is the preview.
        await Assert.That(missing).IsEquivalentTo(["pub"]);
    }

    [Test]
    public async Task EverySampleIsPublished()
    {
        foreach (var sample in Registry.Samples)
        {
            await Assert.That(File.Exists(Path.Combine(Fixtures.Wwwroot, sample.AssetUrl))).IsTrue();
            await Assert.That(Registry.Detect(sample.FileName, Fixtures.Asset(sample.AssetUrl))).IsNotNull();
        }
    }

    [Test]
    public async Task MultiToolPairsOrderByPriority()
    {
        var docxPdf = Registry.TargetsFor(FileTypes.Docx)
            .SelectMany(_ => _.Targets)
            .Single(_ => _.Target == FileTypes.Pdf);
        await Assert.That(docxPdf.Conversions.Select(_ => _.Tool.Id)).IsEquivalentTo(["morph", "officeimo"]);
        await Assert.That(docxPdf.Conversions[0].Tool.Id).IsEqualTo("morph");

        var mdHtml = Registry.TargetsFor(FileTypes.Markdown)
            .SelectMany(_ => _.Targets)
            .Single(_ => _.Target == FileTypes.Html);
        await Assert.That(mdHtml.Conversions[0].Tool.Id).IsEqualTo("markdig");
    }

    [Test]
    [Arguments("map.json", """{"type":"FeatureCollection","features":[]}""", "geojson")]
    [Arguments("map.json", """{"arcs":[],"type":"Topology"}""", "topojson")]
    [Arguments("data.json", """{"name":"x"}""", "json")]
    [Arguments("a.DOCX", "", "docx")]
    [Arguments("diagram.mmd", "flowchart LR", "mermaid")]
    public async Task Detect(string fileName, string content, string? expected)
    {
        var type = Registry.Detect(fileName, Encoding.UTF8.GetBytes(content));
        await Assert.That(type?.Id).IsEqualTo(expected);
    }

    [Test]
    public async Task DuplicateConversionIdsThrow()
    {
        var registry = new ConversionRegistry();
        // A pack instance of its own: registering stamps the owning pack onto the conversion.
        var conversion = ConvertServiceCollectionExtensions.BuildRegistry([new MarkdigPack()]).Conversions[0];
        registry.Add(conversion);
        await Assert.That(() => registry.Add(conversion)).Throws<InvalidOperationException>();
    }
}
